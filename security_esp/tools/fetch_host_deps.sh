#!/usr/bin/env bash
# Reproducible fetch of pinned host-test dependencies (Unity + cJSON).
# Does NOT vendor ESP-IDF — that lives outside the repo (see firmware/BUILD.md).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TP="$SCRIPT_DIR/../third_party"

UNITY_TAG="v2.6.1"
UNITY_URL="https://github.com/ThrowTheSwitch/Unity.git"
CJSON_TAG="v1.7.18"
CJSON_URL="https://github.com/DaveGamble/cJSON.git"

mkdir -p "$TP"

fetch_one() {
    local name="$1" url="$2" tag="$3" dest="$4"
    if [ -d "$dest/.git" ]; then
        echo "== $name already present at $dest — checking out $tag =="
        git -C "$dest" fetch --tags --depth 1 origin "refs/tags/$tag:refs/tags/$tag" 2>/dev/null || true
        git -C "$dest" checkout -q "$tag"
    else
        echo "== cloning $name $tag =="
        rm -rf "$dest"
        git clone --branch "$tag" --depth 1 "$url" "$dest"
    fi
    echo "$name @ $(git -C "$dest" rev-parse HEAD) ($tag)"
}

fetch_one "Unity" "$UNITY_URL" "$UNITY_TAG" "$TP/Unity"
fetch_one "cJSON" "$CJSON_URL" "$CJSON_TAG" "$TP/cJSON"

# Write a lockfile for rebuildability audits.
cat > "$TP/HOST_DEPS.lock" <<EOF
# Generated by security_esp/tools/fetch_host_deps.sh — do not edit by hand.
Unity.tag=$UNITY_TAG
Unity.commit=$(git -C "$TP/Unity" rev-parse HEAD)
cJSON.tag=$CJSON_TAG
cJSON.commit=$(git -C "$TP/cJSON" rev-parse HEAD)
EOF

echo "Host deps ready. Lockfile: $TP/HOST_DEPS.lock"
